"""Persist an opt-in, reproducible contract-only Tach policy in a consumer."""
from __future__ import annotations

from collections.abc import Callable
from pathlib import Path
from typing import Any, cast

import tomlkit

from quard._common import atomic_write, read_json
from quard.architecture_draft.folder_boundary_utils import folder_boundaries
from quard.architecture_draft.configured_architecture_draft import ConfiguredArchitectureDraft
from quard.architecture_draft.generated_selection_utils import (
    IDENTITY, LEGACY_IDENTITY, MARKER, generated, select,
)

__all__ = ["IDENTITY", "MARKER", "generated", "select", "render", "regenerate"]


def render(root: Path) -> tuple[dict[str, Any], str]:
    """Derive boundaries from discovered source without reading old Tach content.

    Args:
        root (Path): Selected project root.

    Returns:
        tuple[dict[str, Any], str]: Native Tach policy and deterministic TOML.
    """
    config = (ConfiguredArchitectureDraft(root).draft(
        contract_only=True, validate_ownership=False)[0]
        if read_json(root / MARKER) == LEGACY_IDENTITY else folder_boundaries(root))
    serialize = cast(Callable[[dict[str, Any]], str], getattr(tomlkit, "dumps"))
    return (config, "# Generated by Quard from contract-only source boundaries. Do not edit.\n"
            + serialize(config))


def regenerate(root: Path) -> bool:
    """Restore the managed Tach config when selected.

    Args:
        root (Path): Selected project root.

    Returns:
        bool: Whether Tach configuration content was changed.
    """
    if not generated(root):
        return False
    _, content = render(root)
    changed = atomic_write(root / "tach.toml", content, root)
    return changed
