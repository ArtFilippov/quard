"""Contract for resolving field access sites against indexed ownership."""
from __future__ import annotations

import ast
from typing import Protocol

from quard.field_ownership.bindings import Binding


class FieldAccess(Protocol):
    """Expose source bindings and diagnostics to the field and call workers."""

    def visit(self, node: ast.AST) -> object: ...
    def results(self) -> list[dict[str, object]]: ...
    def binding(self, name: str) -> Binding | None: ...
    def value(self, node: ast.expr) -> Binding | None: ...
    def builtin_call(self, node: ast.Call, name: str) -> bool: ...
    def annotation(self, node: ast.expr, owner: str | None = None) -> Binding | None: ...
    def assign(self, target: ast.expr, value: Binding | None) -> None: ...
