"""Local interface for contract folders, envelopes and mirrored tests."""
from __future__ import annotations

import ast
from pathlib import Path
from typing import Protocol

from quard.contract_analysis.contract_analysis import ContractAnalysis


_EMPTY_NAMES: frozenset[str] = frozenset()


class FolderAnalysis(ContractAnalysis, Protocol):
    """Extend contract resolution with folder and test-placement operations."""

    def owners(self, name: str, seen: frozenset[str] = _EMPTY_NAMES,
               source: tuple[ast.ClassDef, str] | None = None) -> tuple[set[str], bool]: ...
    def folder(self, contract: str, profile: str) -> Path: ...
    def contract_ancestors(self, name: str, seen: frozenset[str] = _EMPTY_NAMES) -> set[str]: ...
    def envelope_role(self, name: str, node: ast.ClassDef, path: str,
                      seen: frozenset[str] = _EMPTY_NAMES) -> str | None: ...
    def stub_agreement(self, name: str, node: ast.ClassDef, path: str, *,
                       original: ast.ClassDef, source: str) -> bool: ...
    def assembly(self, node: ast.ClassDef, path: str) -> str | None: ...
    def folder_violations(self) -> list[dict[str, object]]: ...
    def base_violations(self, tests: frozenset[str]) -> list[dict[str, object]]: ...
    def module_violations(self, path: str, tree: ast.Module) -> list[dict[str, object]]: ...
    def technical(self, statement: ast.stmt) -> bool: ...
    def eager(self, node: ast.AST) -> list[ast.AST]: ...
    def shadowed(self, node: ast.AST) -> bool: ...
    def signature(self, args: ast.arguments) -> tuple[object, ...]: ...
    def delegation(self, name: str, node: ast.ClassDef, path: str) -> str | None: ...
    def member_kind(self, name: str, method: ast.FunctionDef | ast.AsyncFunctionDef,
                    path: str) -> str | None: ...
    def forwarded(self, method: ast.FunctionDef | ast.AsyncFunctionDef, field: str,
                  kind: str) -> bool: ...
    def property_forwarded(self, method: ast.FunctionDef | ast.AsyncFunctionDef,
                           field: str, kind: str) -> bool: ...
    def is_contract(self, name: str) -> bool: ...
    def export_contract(self, target: str) -> bool: ...
    def conflicting_base(self, name: str, path: str) -> bool: ...
