"""Persist an opt-in, reproducible contract-only Tach policy in a consumer."""
from __future__ import annotations

from collections.abc import Callable
from pathlib import Path
from typing import Any, cast

import tomlkit

from eryx._common import EryxError, atomic_write, read_json, write_json
from eryx.architecture_draft.configured_architecture_draft import ConfiguredArchitectureDraft
from eryx.clean_architecture_layers.configured_clean_architecture_layers import (
    ConfiguredCleanArchitectureLayers,
)


MARKER = ".eryx/architecture.generated.json"
IDENTITY = {"policy": "contract-only", "version": 1}


def generated(root: Path) -> bool:
    """Check the versioned policy selection, rejecting unknown formats.

    Args:
        root (Path): Selected project root.

    Returns:
        bool: Whether generated policy is selected.

    Raises:
        EryxError: The marker has an unrecognized schema.
    """
    path = root / MARKER
    if not path.exists():
        return False
    if read_json(path) != IDENTITY:
        raise EryxError("INVALID_GENERATED_ARCHITECTURE",
                        f"Invalid generated policy marker: {path}")
    return True


def select(root: Path) -> bool:
    """Select generation for a fresh install; keep existing native policies.

    Args:
        root (Path): Selected project root.

    Returns:
        bool: Whether this installation uses generated architecture.
    """
    if generated(root):
        return True
    if (root / "tach.toml").exists() or (root / ".eryx/architecture.ready.json").exists():
        return False
    _ = write_json(root / MARKER, IDENTITY, root)
    return True


def render(root: Path) -> tuple[dict[str, Any], str]:
    """Derive boundaries from discovered source without reading old Tach content.

    Args:
        root (Path): Selected project root.

    Returns:
        tuple[dict[str, Any], str]: Native Tach policy and deterministic TOML.
    """
    config, _ = ConfiguredArchitectureDraft(root).draft(
        contract_only=True, validate_ownership=False)
    serialize = cast(Callable[[dict[str, Any]], str], getattr(tomlkit, "dumps"))
    return (config, "# Generated by Eryx from contract-only source boundaries. Do not edit.\n"
            + serialize(config))


def regenerate(root: Path) -> bool:
    """Restore the managed config and native layer map when selected.

    Args:
        root (Path): Selected project root.

    Returns:
        bool: Whether Tach configuration content was changed.
    """
    if not generated(root):
        return False
    config, content = render(root)
    changed = atomic_write(root / "tach.toml", content, root)
    ConfiguredCleanArchitectureLayers().sync(root, config)
    return changed
