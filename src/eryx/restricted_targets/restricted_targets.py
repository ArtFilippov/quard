"""Contract for declaration evidence and restricted-target resolution."""
from __future__ import annotations

import ast
from typing import Protocol, TypeAlias

from eryx.field_ownership.bindings import Binding

Parents: TypeAlias = dict[str, tuple[str | None, ...]]


class RestrictedTargets(Protocol):
    """Expose declared restrictions and resolved dispatch targets to call analysis."""

    def known_class(self, owner: str) -> bool: ...
    def class_field_type(self, owner: str, name: str) -> Binding | None: ...
    def member(self, binding: Binding | None, name: str) -> Binding | None: ...
    def direct_field(self, owner: str, name: str) -> bool: ...
    def direct_parent(self, owner: str) -> str | None: ...
    def resolved_base(self, owner: str, base: ast.expr, path: str | None = None) -> str | None: ...
    def contract_node(self, name: str | None) -> ast.ClassDef | None: ...
    def contract_source_path(self, name: str) -> str | None: ...
    def contract_declarations(self) -> tuple[tuple[str, ast.ClassDef, str], ...]: ...
    def is_contract(self, name: str, source: tuple[ast.ClassDef, str] | None = None) -> bool: ...
    def decorator_is_instance(self, node: ast.expr) -> bool: ...
    def report_evidence(self) -> tuple[list[dict[str, object]], list[dict[str, object]],
                                       dict[str, str]]: ...

    def instance_type(self, qualified: str | None) -> Binding | None: ...
    def target(self, owner: str, name: str) -> str | None: ...
    def property_target(self, owner: str, name: str) -> str | None: ...
    def special_target(self, owner: str, name: str) -> str | None: ...
    def special_method(self, owner: str, name: str) -> str | None: ...
    def special_lookup(self, owner: str, name: str) -> tuple[str | None, bool]: ...
    def truth_method(self, owner: str) -> str | None: ...
    def comparison_method(self, owner: str, name: str) -> str: ...
    def method_outcome(self, owner: str, name: str) -> str: ...
    def has_attribute(self, owner: str, name: str) -> bool: ...
    def custom_attribute_lookup(self, owner: str) -> bool: ...
    def contract_target(self, owner: str, name: str, property_access: bool = False) -> str | None: ...
    def mro(self, owner: str, visiting: frozenset[str] | None = None) -> list[str] | None: ...
    def field_type(self, owner: str, name: str) -> Binding | None: ...
    def return_type(self, owner: str, name: str, property_only: bool = False) -> Binding | None: ...
    def protocol_return_type(self, owner: str, name: str) -> Binding | None: ...
    def protocol_returns_self(self, owner: str, name: str) -> bool: ...
